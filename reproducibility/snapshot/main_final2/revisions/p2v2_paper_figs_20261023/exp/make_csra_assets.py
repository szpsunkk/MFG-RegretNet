"""LaTeX rows and the supplementary table for CSRA under its two release rules (Claude, 2026-10-23).

Input: p2v2_auction_side_20261022/results_local/csra_declared.json (csra_declared.py; the release-1/(N-k) rule
reproduces the manuscript's CSRA rows, which the script checks again here). Output, in --out:
  csra_rq1_rows.tex   two rows of Table rq1 (B = 25): regret (1e-3), IR violation, budget use
  csra_rq3_rows.tex   two rows of Table rq3-efficiency: budget use range, IR violation, welfare at B = 25..100
  csra_supp_table.tex tabular of Supplementary Table csra-declared
Usage: python make_csra_assets.py --input .../csra_declared.json --out DIR
"""
import argparse
import hashlib
import json
from pathlib import Path

RQ3_MANUSCRIPT = {25: 17.14, 50: 29.56, 75: 39.56, 100: 47.50}   # Table rq3-efficiency, CSRA row
LABEL = {"adapted": r"CSRA, release $1/(N{-}k)$", "declared": r"CSRA, declared release"}


def pct(x):
    return "0" if x == 0 else f"{100 * x:.1f}\\%"


def reg(x):
    return f"{x:.0f}" if x >= 100 else f"{x:.1f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    d = json.loads(Path(a.input).read_text())
    if d["profiles"] != 10000 or d["check_vs_original"] != 0.0:
        raise SystemExit("unexpected input")
    R, Q = d["results"], d["rq3"]
    for B in (25, 50):
        mine, paper = R[f"B{B}_adapted"], R[f"B{B}_manuscript_row"]
        for k in ("regret_mean_x1e3", "budget_used", "released_eps_sum"):
            if abs(mine[k] - paper[k]) > 1e-4 * max(1.0, abs(paper[k])):
                raise SystemExit(f"B={B} {k}: {mine[k]} differs from the manuscript row {paper[k]}")
        if abs(mine["ir_violation_rate"] - paper["ir_violation_rate"]) > 1e-6:
            raise SystemExit(f"B={B}: IR rate differs from the manuscript row")
    for B, sw in RQ3_MANUSCRIPT.items():
        if f"{Q[f'B{B}_adapted']['welfare']:.2f}" != f"{sw:.2f}":
            raise SystemExit(f"B={B}: welfare {Q[f'B{B}_adapted']['welfare']} differs from the manuscript {sw}")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    head = f"% generated by make_csra_assets.py from {Path(a.input).name} (sha256 {hashlib.sha256(Path(a.input).read_bytes()).hexdigest()[:16]})\n"

    rq1 = [head]
    for rule in ("adapted", "declared"):
        r = R[f"B25_{rule}"]
        rq1.append(f"  {LABEL[rule]} & ${reg(r['regret_mean_x1e3'])}$ & {pct(r['ir_violation_rate'])} & "
                   f"{r['budget_used']:.3f} \\\\\n")
    (out / "csra_rq1_rows.tex").write_text("".join(rq1))

    rq3 = [head]
    for rule in ("adapted", "declared"):
        used = [Q[f"B{B}_{rule}"]["budget_used"] for B in (25, 50, 75, 100)]
        ir = [Q[f"B{B}_{rule}"]["ir_violation_rate"] for B in (25, 50, 75, 100)]
        ir_txt = "2.6\\%" if rule == "adapted" else pct(max(ir))   # adapted: the manuscript's value is kept
        sw = " & ".join(f"{Q[f'B{B}_{rule}']['welfare']:.2f}" for B in (25, 50, 75, 100))
        rq3.append(f"  {LABEL[rule]} & {min(used):.2f}--{max(used):.2f} & {ir_txt} & {sw} \\\\\n")
    (out / "csra_rq3_rows.tex").write_text("".join(rq3))

    t = [head, "\\begin{tabular}{lcccc}\n\\toprule\n",
         " & \\multicolumn{2}{c}{Release $1/(N{-}k)$} & \\multicolumn{2}{c}{Declared release} \\\\\n",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n",
         " & $B{=}25$ & $B{=}50$ & $B{=}25$ & $B{=}50$ \\\\\n\\midrule\n"]
    rows = [("Regret ($10^{-3}$)", lambda r: reg(r["regret_mean_x1e3"])),
            ("IR viol.", lambda r: pct(r["ir_violation_rate"])),
            ("$\\mathcal{R}/B$", lambda r: f"{r['budget_used']:.3f}"),
            ("$\\sum_i\\epsilon_i^{\\mathrm{out}}$", lambda r: f"{r['released_eps_sum']:.2f}")]
    for name, f in rows:
        t.append(f"{name} & " + " & ".join(f(R[f"B{B}_{rule}"]) for rule in ("adapted", "declared") for B in (25, 50))
                 + " \\\\\n")
    t += ["\\midrule\n", " & \\multicolumn{4}{c}{$\\overline{\\mathrm{SW}}$ / privacy cost at budget $B$} \\\\\n",
          "\\cmidrule(lr){2-5}\n", " & 25 & 50 & 75 & 100 \\\\\n\\midrule\n"]
    for rule in ("adapted", "declared"):
        name = "Release $1/(N{-}k)$" if rule == "adapted" else "Declared release"
        t.append(name + " & " + " & ".join(f"{Q[f'B{B}_{rule}']['welfare']:.2f} / {Q[f'B{B}_{rule}']['privacy_cost']:.2f}"
                                            for B in (25, 50, 75, 100)) + " \\\\\n")
    t.append("Revenue $\\mathcal{R}$ & " + " & ".join(f"{Q[f'B{B}_adapted']['revenue']:.2f}" for B in (25, 50, 75, 100))
             + " \\\\\n\\bottomrule\n\\end{tabular}\n")
    for B in (25, 50, 75, 100):
        if abs(Q[f"B{B}_adapted"]["revenue"] - Q[f"B{B}_declared"]["revenue"]) > 1e-9:
            raise SystemExit("payments differ between the two rules")
    (out / "csra_supp_table.tex").write_text("".join(t))
    print("written:", sorted(p.name for p in out.glob("csra_*.tex")))


if __name__ == "__main__":
    main()

"""Per-client cumulative privacy of the RQ4 confirmation, from the Stage 3 ledgers (no accuracy is read).

For every setting and arm (ours and the ten external arms), over the three seeds: each client's cumulative
(epsilon, delta = 1e-5) add/remove after 100 rounds (RDP composition, privacy.json of each run), and its number of
participations. Reports the mean, the 95th percentile and the maximum over the 30 client-seed pairs, and the
mean participations per client. Requested by the external review: matched mean privacy per round does not imply
the same exposure per client.
Usage: python rq4_privacy.py --base ... --old ... --decision ... --out DIR [--remap OLD=NEW]
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from rq4_fill import CANDIDATE, DISPLAY, EXTERNAL, read

ARMS = (CANDIDATE, *EXTERNAL)


def cell_key(c):
    return (c["dataset"], float(c["alpha"]), c["mode"], float(c["value"]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--old", required=True)
    ap.add_argument("--decision", required=True, help="rq4_recomputed.json (best external arm per setting)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--remap", default="")
    a = ap.parse_args()
    jobs = read(Path(a.base) / "jobs_stage3_v2.json") + read(Path(a.old) / "jobs_stage3_early.json")
    if a.remap:
        src, dst = a.remap.split("=", 1)
        for j in jobs:
            j["done"] = dst + j["done"][len(src):] if j["done"].startswith(src) else j["done"]
    per = defaultdict(lambda: {"eps": [], "part": [], "seeds": []})
    for j in jobs:
        if j["arm"] not in ARMS:
            continue
        led = read(Path(j["done"]).with_name("privacy.json"))
        if led.get("delta_add_remove") != 1e-5 or not led.get("all_accountant_parity_pass"):
            raise SystemExit(f"{j['id']}: unexpected ledger")
        k = (cell_key(j["cell"]), j["arm"])
        per[k]["eps"] += [c["epsilon_add_remove"] if c["participations"] else 0.0 for c in led["clients"]]
        per[k]["part"] += [c["participations"] for c in led["clients"]]
        per[k]["seeds"].append(j["seed"])
    rows = {}
    for (cell, arm), v in per.items():
        if sorted(v["seeds"]) != [231, 232, 233]:
            continue
        e = np.asarray(v["eps"])
        rows[f"{cell}|{arm}"] = {"cell": list(cell), "arm": arm, "eps_mean": float(e.mean()),
                                 "eps_p95": float(np.quantile(e, .95, method="higher")), "eps_max": float(e.max()),
                                 "participations_mean": float(np.mean(v["part"]))}
    dec = read(a.decision)["decision"]["per_cell"]
    table = [r"\begin{tabular}{lcccclcccc}", r"\toprule",
             r"& \multicolumn{4}{c}{MFG-RegretNet} & \multicolumn{5}{c}{Best external mechanism} \\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-10}",
             r"Setting & mean & P95 & max & rounds & mechanism & mean & P95 & max & rounds \\", r"\midrule"]
    for r in dec:
        cell = tuple(r["cell"])
        o, x = rows.get(f"{cell}|{CANDIDATE}"), rows.get(f"{cell}|{r['external_arm']}")
        ds = "CIFAR-10" if cell[0] == "CIFAR10" else cell[0]
        name = (rf"{ds}, $\alpha{{=}}{cell[1]:g}$, " + (rf"$B{{=}}{cell[3]:g}$" if cell[2] == "budget"
                                                        else rf"$\bar\epsilon{{=}}{cell[3]:g}$"))
        f = lambda d: f"{d['eps_mean']:.1f} & {d['eps_p95']:.1f} & {d['eps_max']:.1f} & {d['participations_mean']:.0f}"
        table.append(f"{name} & {f(o)} & {DISPLAY[r['external_arm']]} & {f(x)} \\\\")
    table += [r"\bottomrule", r"\end{tabular}"]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "rq4_privacy.json").write_text(json.dumps(rows, indent=1))
    (out / "rq4_privacy_table.tex").write_text("% generated by rq4_privacy.py from the Stage 3 ledgers\n" + "\n".join(table) + "\n")
    print("settings x arms:", len(rows))


if __name__ == "__main__":
    main()
